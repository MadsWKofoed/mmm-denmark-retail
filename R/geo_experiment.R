# =============================================================================
# R/geo_experiment.R
#
# Simulated geo experiment: social_prospecting switched off in a randomly
# chosen half of Denmark's 98 municipalities for a 6-week window. Real
# municipality names, SIMULATED population weights (not fetched real
# population data -- documented here and in the script that uses this).
#
# This module IS allowed to use ground truth (config/ground_truth.yml, the
# true weekly contribution of social_prospecting) to construct the
# experiment's synthetic outcome data -- exactly as a real experiment's
# outcome data is generated by the real (unknown-to-the-analyst) causal
# effect. What must stay blind to ground truth is the DiD ESTIMATION that
# follows, in scripts/07_geo_experiment.R, which only ever sees the
# simulated panel, never the true parameters directly.
# =============================================================================

#' The 98 Danish municipalities (2007 structural-reform boundaries, stable
#' since), grouped by region, with a SIMULATED population weight for this
#' experiment (not real population figures).
danish_municipalities <- function(seed) {
  hovedstaden <- c("Albertslund", "Alleroed", "Ballerup", "Bornholm", "Broendby", "Dragoer", "Egedal",
                    "Fredensborg", "Frederiksberg", "Frederikssund", "Furesoe", "Gentofte", "Gladsaxe",
                    "Glostrup", "Gribskov", "Halsnaes", "Helsingoer", "Herlev", "Hilleroed", "Hvidovre",
                    "Hoeje-Taastrup", "Hoersholm", "Ishoej", "Koebenhavn", "Lyngby-Taarbaek", "Rudersdal",
                    "Roedovre", "Taarnby", "Vallensbaek")
  sjaelland <- c("Faxe", "Greve", "Guldborgsund", "Holbaek", "Kalundborg", "Koege", "Lejre", "Lolland",
                 "Naestved", "Odsherred", "Ringsted", "Roskilde", "Slagelse", "Solroed", "Soroe", "Stevns", "Vordingborg")
  syddanmark <- c("Assens", "Billund", "Esbjerg", "Fanoe", "Fredericia", "Faaborg-Midtfyn", "Haderslev",
                  "Kerteminde", "Kolding", "Langeland", "Middelfart", "Nordfyns", "Nyborg", "Odense",
                  "Svendborg", "Soenderborg", "Toender", "Varde", "Vejen", "Vejle", "Aeroe", "Aabenraa")
  midtjylland <- c("Favrskov", "Hedensted", "Herning", "Holstebro", "Horsens", "Ikast-Brande", "Lemvig",
                    "Norddjurs", "Odder", "Randers", "Ringkoebing-Skjern", "Samsoe", "Silkeborg",
                    "Skanderborg", "Skive", "Struer", "Syddjurs", "Viborg", "Aarhus")
  nordjylland <- c("Broenderslev", "Frederikshavn", "Hjoerring", "Jammerbugt", "Laesoe", "Mariagerfjord",
                    "Morsoe", "Rebild", "Thisted", "Vesthimmerland", "Aalborg")

  all_names <- c(hovedstaden, sjaelland, syddanmark, midtjylland, nordjylland)
  stopifnot(length(all_names) == 98)

  set.seed(seed)
  # A handful of genuinely large cities get an explicit population boost;
  # everything else draws from a lognormal distribution -- illustrative,
  # not real ONS/DST population figures.
  big_cities <- c(Koebenhavn = 650000, Aarhus = 355000, Odense = 205000, Aalborg = 220000,
                   Esbjerg = 115000, Randers = 100000, Kolding = 95000, Horsens = 92000,
                   Vejle = 115000, Roskilde = 90000)
  pop <- setNames(numeric(length(all_names)), all_names)
  pop[names(big_cities)] <- big_cities
  remaining <- setdiff(all_names, names(big_cities))
  pop[remaining] <- round(exp(rnorm(length(remaining), log(28000), 0.7)))

  tibble::tibble(municipality = all_names, population = pop[all_names]) |>
    dplyr::mutate(pop_share = population / sum(population))
}

#' Randomly assign municipalities to treatment (prospecting switched off) vs
#' control, a simple random half-split (not stratified -- per the brief).
assign_treatment <- function(muni_df, seed) {
  set.seed(seed)
  n <- nrow(muni_df)
  treated_idx <- sample(seq_len(n), size = floor(n / 2))
  muni_df$treated <- FALSE
  muni_df$treated[treated_idx] <- TRUE
  muni_df
}

#' Build the municipality x week experiment panel (per-capita revenue),
#' using the TRUE weekly contribution of social_prospecting to construct
#' outcomes -- see module docstring for why this is legitimate here.
#'
#' @param wt_truth Weekly TRUE table (data/processed/_truth/weekly_truth.rds).
#' @param muni_df Municipality metadata with treated flags (see above).
#' @param pre_weeks,post_weeks Number of pre-/post-period weeks in the panel.
#' @param window_end_week_index Row index (into wt_truth) of the LAST pre-period week.
#' @param noise_sd Idiosyncratic per-muni-week noise (per-capita revenue units).
#' @param muni_fe_sd SD of municipality fixed effects (per-capita heterogeneity).
simulate_geo_panel <- function(wt_truth, muni_df, pre_weeks, post_weeks, window_end_week_index,
                                noise_sd = 0.06, muni_fe_sd = 0.15, seed) {
  set.seed(seed)
  total_pop <- sum(muni_df$population)
  weeks_idx <- seq(window_end_week_index - pre_weeks + 1, window_end_week_index + post_weeks)
  panel_weeks <- wt_truth[weeks_idx, ]

  muni_fe <- stats::setNames(rnorm(nrow(muni_df), 0, muni_fe_sd), muni_df$municipality)

  purrr::map_dfr(seq_len(nrow(panel_weeks)), function(w) {
    row <- panel_weeks[w, ]
    is_post <- w > pre_weeks
    baseline_pc <- (row$revenue_dkk - row$true_contrib_social_prospecting) / total_pop
    contrib_pc <- row$true_contrib_social_prospecting / total_pop

    purrr::map_dfr(seq_len(nrow(muni_df)), function(i) {
      m <- muni_df[i, ]
      suppress <- is_post && m$treated
      revenue_pc <- baseline_pc * exp(muni_fe[[m$municipality]]) +
        contrib_pc * (if (suppress) 0 else 1) +
        rnorm(1, 0, noise_sd * baseline_pc)
      tibble::tibble(
        municipality = m$municipality, population = m$population, treated = m$treated,
        week_index = w, week_start = row$week_start, is_post = is_post,
        week_rel = w - pre_weeks - 1,  # -1 = last pre-period week (event-study reference)
        revenue_pc = revenue_pc
      )
    })
  })
}
